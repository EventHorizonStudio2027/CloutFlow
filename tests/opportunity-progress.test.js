const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const progress=require('../assets/js/opportunity-progress');
const popup=require('../assets/js/opportunity-popups');
const values=new Map();const store={getItem:k=>values.has(k)?values.get(k):null,setItem:(k,v)=>values.set(k,v)};
assert.deepEqual(progress.read(store),{});
assert.equal(progress.set(store,'multistream','interested'),true);
assert.equal(progress.get(store,'multistream'),'interested');
assert.equal(progress.set(store,'multistream','trying'),true);
assert.equal(progress.set(store,'multistream','doing'),true);
assert.equal(progress.set(store,'multistream','invalid'),false);
assert.equal(progress.set(store,'<bad>','doing'),false);
assert.equal(progress.get(store,'multistream'),'doing');
assert.equal(popup.eligible([{id:'multistream'},{id:'clips'}],store).length,1);
assert.equal(popup.eligible([{id:'multistream'},{id:'clips'}],store)[0].id,'clips');
assert.equal(progress.filter([{id:'multistream'},{id:'clips'}],store,'doing').length,1);
assert.equal(progress.filter([{id:'multistream'},{id:'clips'}],store,'not-started').length,1);
assert.deepEqual(progress.summary([{id:'multistream'},{id:'clips'}],store),{'all':2,'not-started':1,interested:0,trying:0,doing:1});
assert.equal(progress.filter([{id:'multistream'}],store,'unknown').length,1);
assert.equal(progress.set(store,'multistream',''),true);
assert.equal(popup.eligible([{id:'multistream'}],store).length,1);
values.set(progress.key,'{bad json');assert.deepEqual(progress.read(store),{});

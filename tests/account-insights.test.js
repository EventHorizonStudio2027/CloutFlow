const assert=require('node:assert/strict');
const A=require('../assets/js/account-insights.js');
const entry=(platform,account,currency,gross,fee=0)=>({platform,account,currency,gross,fee});
const earnings=[entry('YouTube','Main','USD',100,10),entry('Twitch','Main','USD',80,5),entry('YouTube','Main','EUR',40,2)];
const adjustments=[{platform:'YouTube',account:'Main',currency:'USD',amount:-12},{platform:'Twitch',account:'Main',currency:'USD',amount:-4}];
const deposits=[{platform:'YouTube',account:'Main',currency:'USD',amount:55},{platform:'YouTube',account:'Main',currency:'EUR',amount:25}];
const net=e=>e.gross-e.fee;
assert.notEqual(A.key('YouTube','Main'),A.key('Twitch','Main'));
assert.deepEqual(JSON.parse(A.key('YouTube','Main')),['YouTube','Main']);
const c=A.choices(earnings,adjustments,deposits,[{platform:'Apple',name:'Unused'}]);
assert.equal(c.length,3);
const rows=A.summarize(A.key('YouTube','Main'),earnings,adjustments,deposits,net);
assert.equal(rows.length,2);
assert.deepEqual(rows.map(r=>r.currency),['EUR','USD']);
assert.equal(rows[1].gross,100);
assert.equal(rows[1].net,90);
assert.equal(rows[1].adjustments,-12);
assert.equal(rows[1].adjustedNet,78);
assert.equal(rows[1].deposits,55);
assert.equal(rows[1].transactions,1);
assert.equal(rows[0].adjustedNet,38);
assert.equal(rows[0].deposits,25);
assert.deepEqual(A.summarize(A.key('YouTube','Unknown'),earnings,adjustments,deposits,net),[]);
console.log('Account insights tests passed');

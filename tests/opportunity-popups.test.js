const assert=require('node:assert/strict');
const p=require('../assets/js/opportunity-popups.js');
const values={};const store={getItem:k=>values[k]??null,setItem:(k,v)=>{values[k]=v}};
const ideas=[{id:'stream',already:false},{id:'other',already:false},{id:'existing',already:true}];
assert.deepEqual(p.eligible(ideas,store,1000).map(i=>i.id),['stream','other']);
p.snooze('stream',store,1000,30);
assert.deepEqual(p.eligible(ideas,store,1001).map(i=>i.id),['other']);
assert.deepEqual(p.eligible(ideas,store,1000+31*86400000).map(i=>i.id),['stream','other']);
values[p.key]='not-json';assert.equal(p.eligible(ideas,store,1000).length,2);
assert.equal(p.present([],null,store),false);
assert.equal(p.disabled(store),false);
assert.equal(p.setEnabled(store,false),true);
assert.equal(p.disabled(store),true);
assert.equal(p.setEnabled(store,true),true);
assert.equal(p.disabled(store),false);
const state={};const activityStore={getItem:k=>state[k]??null,setItem:(k,v)=>state[k]=v};
const twitch=[{matchedPlatforms:['Twitch','YouTube']}];
assert.deepEqual(p.activity(twitch),['twitch','youtube']);
assert.deepEqual(p.detectNewPlatforms(twitch,activityStore),[],'first activity establishes a baseline');
assert.deepEqual(p.detectNewPlatforms(twitch,activityStore),[],'unchanged activity has no new platforms');
assert.deepEqual(p.detectNewPlatforms([{matchedPlatforms:['Twitch','YouTube','Kick']}],activityStore),['kick']);
assert.deepEqual(p.detectNewPlatforms([{matchedPlatforms:['Kick']}],activityStore),[],'removed platforms are not new');
assert.deepEqual(p.detectNewPlatforms([{matchedPlatforms:['Kick','Twitch']}],activityStore),['twitch']);
assert.equal(p.recentlyShown(activityStore,100000),false);
activityStore.setItem(p.lastKey,'100000');
assert.equal(p.recentlyShown(activityStore,100001),true);
assert.equal(p.recentlyShown(activityStore,100000+p.cooldownMs),false);
assert.equal(p.recentlyShown(activityStore,100000+p.cooldownMs-1),true);
assert.equal(p.recentlyShown(activityStore,100000+p.cooldownMs+1),false);
const milestoneStoreData={};const milestoneStore={getItem:k=>milestoneStoreData[k]??null,setItem:(k,v)=>{milestoneStoreData[k]=v}};
const sponsor={incomeType:'Sponsorship',platform:'Twitch'};
assert.deepEqual(p.milestoneTypes([sponsor,{incomeType:'Affiliate commissions'},{incomeType:'Subscriptions'}]),['affiliate','membership','sponsor']);
assert.deepEqual(p.detectMilestones([sponsor],milestoneStore),[],'existing earnings establish a baseline');
assert.deepEqual(p.detectMilestones([sponsor,{incomeType:'Affiliate commissions'}],milestoneStore),['affiliate']);
assert.deepEqual(p.detectMilestones([sponsor,{incomeType:'Affiliate commissions'}],milestoneStore),[],'unchanged milestones never repeat');
assert.deepEqual(p.detectMilestones([sponsor,{incomeType:'Affiliate commissions'},{incomeType:'Gifted subscriptions'}],milestoneStore),['membership','tips']);
assert.deepEqual(p.detectMilestones([],milestoneStore),[]);
assert.deepEqual(p.detectMilestones([sponsor],milestoneStore),['sponsor'],'newly reintroduced type can be detected');
console.log('Opportunity popup tests passed');

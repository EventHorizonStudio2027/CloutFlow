const assert=require('node:assert/strict');
const R=require('../assets/js/platform-rankings.js');
const net=e=>e.gross-e.fees;
const earned=[{platform:'YouTube',currency:'USD',gross:120,fees:20},{platform:'Twitch',currency:'USD',gross:80,fees:0},{platform:'YouTube',currency:'EUR',gross:500,fees:0},{platform:'YouTube',currency:'USD',gross:30,fees:0}];
const adj=[{platform:'YouTube',currency:'USD',amount:-100},{platform:'Twitch',currency:'USD',amount:5},{platform:'TikTok',currency:'USD',amount:-5}];
const rows=R.summarize(earned,adj,net);
assert.deepEqual(rows.map(x=>[x.currency,x.platform,x.adjustedNet]),[['EUR','YouTube',500],['USD','Twitch',85],['USD','YouTube',30],['USD','TikTok',-5]]);
assert.equal(rows.find(x=>x.currency==='USD'&&x.platform==='YouTube').transactions,2);
assert.equal(rows.find(x=>x.platform==='TikTok').transactions,0);
assert.deepEqual(R.summarize([],[],net),[]);
assert.equal(R.summarize([{platform:'X',currency:'USD',gross:0,fees:0}],[],net)[0].adjustedNet,0);
const shares=R.analyze(rows.filter(r=>r.currency==='USD'));
assert.equal(shares.positiveTotal,115);
assert.equal(shares.leader.platform,'Twitch');
assert.ok(Math.abs(shares.leaderShare-85/115*100)<1e-8);
assert.equal(shares.topThreeShare,100);
assert.equal(shares.shares.get('TikTok'),0);
const zero=R.analyze([{platform:'Loss',adjustedNet:-20},{platform:'Zero',adjustedNet:0}]);
assert.equal(zero.positiveTotal,0);
assert.equal(zero.leader,null);
assert.equal(zero.leaderShare,null);
assert.equal(zero.shares.get('Loss'),null);
assert.equal(R.analyze([]).topThreeShare,null);
console.log('Platform rankings and revenue concentration tests passed');

const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {suggest}=require('../assets/js/income-opportunities.js');
const stream=[{platform:'Twitch',channel:'stream',type:'Subscriptions',gross:100}];
const ideas=suggest(stream);
assert(ideas.some(x=>x.id==='multistream'),'streamer should see multistream idea');
assert(ideas.some(x=>x.id==='clips'),'streamer should see clip repurposing');
assert(ideas.some(x=>x.id==='sponsors'),'streamer should see sponsorships');
assert(ideas.find(x=>x.id==='memberships').already,'existing subscription should be recognized');
assert(!ideas.some(x=>x.id==='app-iap'),'streamer should not get app-store-specific advice');
assert(suggest([{platform:'Apple App Store',channel:'app',type:'Paid downloads'}]).some(x=>x.id==='app-sub'));
assert(suggest([{platform:'Shopify',channel:'commerce',type:'Product sales'}]).some(x=>x.id==='store-bundle'));
assert(suggest([]).length===0,'no activity should yield onboarding state');
assert(suggest([],[{platform:'YouTube',channel:'stream',name:'Main'}]).some(x=>x.id==='multistream'),'account alone should personalize');
assert(suggest(stream,[],'products').every(x=>x.group==='products'));
assert(!suggest(stream,[],'live').some(x=>x.group!=='live'));
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(html.includes('id="incomeOpportunityResults"'));
assert(html.includes('assets/js/income-opportunities.js'));
console.log('Income opportunity recommendation tests passed');

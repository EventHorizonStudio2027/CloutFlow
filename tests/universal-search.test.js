const assert=require('node:assert/strict');
const {match}=require('../assets/js/universal-search.js');
const data=[{label:'Transaction ledger',detail:'Income'},{label:'Payout center',detail:'Deposits'},{label:'Creator accounts',detail:'Profiles'}];
assert.deepEqual(match(data,'payout').map(x=>x.label),['Payout center']);
assert.deepEqual(match(data,'creator accounts').map(x=>x.label),['Creator accounts']);
assert.deepEqual(match(data,'INCOME').map(x=>x.label),['Transaction ledger']);
assert.equal(match(data,'not found').length,0);
const fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../assets/js/universal-search.js'),'utf8');
assert.match(source,/const query=input\.value\.trim\(\);close\(\)/,'Search term must be captured before closing palette');
assert.match(source,/host\.addEventListener\('keydown'/,'Keyboard focus must be contained in palette');
assert.match(source,/new doc\.defaultView\.Event\('input'/,'Use the owning document event constructor');
assert.match(source,/trigger\.title='Search \(⌘K \/ Ctrl\+K\)'/,'Show cross-platform keyboard shortcut');
console.log('Universal search matching and keyboard regression: passed');
